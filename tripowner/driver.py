"""The driver on the other end. Scripted (offline phrasebook), a pre-generated pool of varied lines,
or a live LLM persona."""
import json
import logging
import random
from pathlib import Path

from .config import settings
from .i18n import LANG_NAMES, render
from .llm import get_llm

log = logging.getLogger(__name__)

INTENTS = {
    "where": "Ask the rider where exactly they are; you can't find them.",
    "phone": "Ask the rider for their personal phone number.",
    "coming": "Say okay, you understood, you're coming there now.",
    "near_signal": "Say you're stuck near the signal, two more minutes.",
    "arrived": "Say you've arrived and are waiting near the gate.",
}


class ScriptedDriver:
    async def say(self, intent: str, lang: str) -> str:
        return render(f"driver.{intent}", lang)


POOL_PATH = Path(__file__).resolve().parent / "sim" / "driver_lines.json"


def load_pool(path: Path = POOL_PATH) -> dict:
    """{intent: {lang: [{"text": native, "en": english}]}}, generated by sim/gen_driver_lines.py."""
    return json.loads(path.read_text(encoding="utf-8"))


class PoolDriver(ScriptedDriver):
    """Varied, natural driver lines from a fixed pool. The nth time a driver has a given intent in a given
    language, the same seed picks the same line, so every agent in an eval hears exactly the same words."""

    def __init__(self, pool: dict, seed: int):
        self.pool = pool
        self.seed = seed
        self._seen: dict[tuple[str, str], int] = {}

    async def say(self, intent: str, lang: str) -> str:
        options = self.pool.get(intent, {}).get(lang)
        if not options:
            return await super().say(intent, lang)
        n = self._seen.get((intent, lang), 0)
        self._seen[(intent, lang)] = n + 1
        return random.Random(f"{self.seed}:{intent}:{lang}:{n}").choice(options)["text"]


class LLMDriver(ScriptedDriver):
    """Natural, varied driver lines. Needs Sarvam on for translation (phrasebook won't match)."""

    def __init__(self, llm):
        self.llm = llm

    async def say(self, intent: str, lang: str) -> str:
        try:
            msg = await self.llm.chat([
                {"role": "system", "content": (
                    f"You are a Bengaluru cab driver on a call with your rider. Speak casual, everyday "
                    f"{LANG_NAMES.get(lang, 'English')} the way drivers really do (mixing English words is fine), "
                    f"written in that language's native script. Reply with ONE short sentence and nothing else."
                )},
                {"role": "user", "content": INTENTS[intent]},
            ], temperature=0.8)
            return msg.get("content") or await super().say(intent, lang)
        except Exception as e:
            log.warning("llm driver failed, using script: %s", e)
            return await super().say(intent, lang)


def make_driver():
    if settings.driver_mode == "pool":
        return PoolDriver(load_pool(), seed=0)
    llm = get_llm()
    if settings.driver_mode == "llm" and llm and settings.sarvam_enabled:
        return LLMDriver(llm)
    return ScriptedDriver()
